// Difficulty report: simulates every campaign level with two player models.
// Run: npm run balance  (writes BALANCE.md)
import { writeFileSync } from 'node:fs';
import { campaignLevel, CAMPAIGN_COUNT, fmtTime } from '../src/levels';
import { simulate, estimateSeconds, Skill } from '../src/sim';
import { layoutSize } from '../src/layouts';
import { mulberry32 } from '../src/rng';

const RUNS = Number(process.env.RUNS ?? 30);
const rows: string[] = [];
const summary: { n: number; casual: number; skilled: number }[] = [];
for (let n = 1; n <= CAMPAIGN_COUNT; n++) {
  const s = campaignLevel(n);
  const rate: Record<Skill, number> = { casual: 0, skilled: 0 };
  const fails: Record<string, number> = {};
  for (const skill of ['casual', 'skilled'] as Skill[]) {
    let wins = 0;
    for (let r = 0; r < RUNS; r++) {
      const res = simulate(s, skill, mulberry32(n * 7919 + r * 104729 + (skill === 'skilled' ? 1 : 0)));
      if (res.outcome === 'won') wins++; else if (skill === 'skilled') fails[res.outcome] = (fails[res.outcome] ?? 0) + 1;
    }
    rate[skill] = Math.round((wins / RUNS) * 100);
  }
  summary.push({ n, ...rate });
  const tiles = layoutSize(s.layout);
  const mech = [s.objective === 'gold' ? `gold×${s.gold}` : '', s.mist ? `mist ${Math.round(s.mist * 100)}%` : '', s.locks ? `locks ${s.locks}` : '',
    s.bombs ? `bombs ${s.bombs}@${s.bombMoves}` : '', s.timeLimit ? `clock ${fmtTime(s.timeLimit)}` : ''].filter(Boolean).join(', ');
  rows.push(`| ${n}${s.boss ? ' ★' : ''} | ${s.name} | ${s.layout} (${tiles}) | ${mech || '—'} | ${s.hints}/${s.shuffles} | ${rate.casual}% | ${rate.skilled}% | ${fmtTime(estimateSeconds(s, tiles))} | ${Object.entries(fails).map(([k, v]) => `${k} ${v}`).join(', ') || '—'} |`);
  process.stdout.write(`\r${n}/${CAMPAIGN_COUNT}`);
}
const world = (w: number, k: 'casual' | 'skilled') => Math.round(summary.slice(w * 10, w * 10 + 10).reduce((a, r) => a + r[k], 0) / 10);
const md = `# Campaign balance report

Generated by \`npm run balance\` (${RUNS} simulated runs per level per player model).

- **Casual**: picks any available pair at random, always takes a bomb pair when one is free, uses shuffles when stuck, never uses hints.
- **Skilled**: looks one move ahead (prefers pairs that free the most tiles), spends hints when a choice between three identical tiles could trap it or a fuse is low.
- **Est. time**: modelled human solve time used to set par and the sand clock.

| World | Casual | Skilled |
|---|---|---|
${Array.from({ length: 8 }, (_, w) => `| ${w + 1} | ${world(w, 'casual')}% | ${world(w, 'skilled')}% |`).join('\n')}

| # | Level | Layout | Mechanics | Hints/Shuffles | Casual win | Skilled win | Est. time | Skilled losses |
|---|---|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync('BALANCE.md', md);
console.log('\n' + Array.from({ length: 8 }, (_, w) => `W${w + 1} casual ${world(w, 'casual')}% skilled ${world(w, 'skilled')}%`).join('\n'));
